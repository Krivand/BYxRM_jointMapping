"""Read-only audit of saved reviewer results and committed source identities."""
import csv
import hashlib
import io
import json
import os
from pathlib import Path
import subprocess

source = Path(__file__).resolve().parent
out = Path(os.environ['ERIS_CARD_OUTPUT']).resolve()
root = Path('/PHShome/kv1026/p05').resolve()
managed = Path('/PHShome_actual/k/kv1026/tools/eris-jobcards')
expected = json.loads((source / 'expected_source.json').read_text())
report = {'reference': expected, 'source_checks': [], 'results': [], 'provenance': [],
          'limitations': ['Matching source bytes does not prove a result was generated by that source.',
             'File timestamps alone do not establish mapping-log/QTL-table provenance.'], 'errors': []}

def blob(data):
    return hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest()

def read_small(path, limit=250000):
    if path.is_symlink() or not path.is_file() or path.stat().st_size > limit:
        return None
    return path.read_bytes()

for base in (root, root / 'code'):
    for name, sha in expected['blobs'].items():
        data = read_small(base / name)
        if data is not None:
            report['source_checks'].append({'path': str(base / name), 'expected_blob': sha,
                'observed_blob': blob(data), 'matches': blob(data) == sha})
for path in (root / 'conventions.md', root / 'AGENTS.md', root.parent / 'conventions.md'):
    data = read_small(path, 50000)
    if data is not None:
        report['provenance'].append({'path': str(path), 'text': data.decode()})

names = {'supported_gene_cis_trans_presence.tsv', 'regulation_denominators.tsv',
    'targeted_fit_counts.tsv', 'random_intercept_variances.tsv',
    'actual_threshold_fit_summary.tsv', 'pairwise_actual_threshold_power.tsv',
    'threshold_full_first_pass_by_study_chr.tsv', 'threshold_selected_full_calls.tsv',
    'simulation_actual_thresholds.tsv', 'simulation_summary.tsv',
    'segregant_dependence_summary.tsv', 'pairwise_power_fit_summary.tsv'}
seen = 0
selected_actions = set()
for base, max_depth in ((root / 'asys/review', 4), (managed / 'actions', 3)):
    if not base.is_dir():
        report['errors'].append('Missing directory: ' + str(base))
        continue
    for directory, dirs, files in os.walk(base, followlinks=False):
        depth = len(Path(directory).relative_to(base).parts)
        dirs[:] = sorted(d for d in dirs if not d.startswith('.') and not (Path(directory) / d).is_symlink()) if depth < max_depth else []
        seen += len(dirs) + len(files)
        if seen > 30000:
            raise RuntimeError('Bounded inventory limit exceeded; no complete audit claimed')
        for name in sorted(set(files) & names):
            path = Path(directory) / name
            data = read_small(path)
            if data is None:
                report['errors'].append('Unreadable or oversized result: ' + str(path))
                continue
            text = data.decode('utf-8')
            rows = list(csv.DictReader(io.StringIO(text), delimiter='\t'))
            report['results'].append({'path': str(path), 'sha256': hashlib.sha256(data).hexdigest(),
                'rows': rows, 'row_count': len(rows)})
            if base == managed / 'actions':
                selected_actions.add(path.relative_to(base).parts[0])

# Inspect only source manifests associated with the selected scientific outputs.
def bundle_ids(value):
    if isinstance(value, str) and value.startswith('bundle_') and len(value) == 71:
        yield value
    elif isinstance(value, dict):
        for item in value.values():
            yield from bundle_ids(item)
    elif isinstance(value, list):
        for item in value:
            yield from bundle_ids(item)

for action in sorted(selected_actions):
    data = read_small(managed / 'actions' / action / 'plan.json', 100000)
    if data is None:
        report['errors'].append('Missing plan: ' + action)
        continue
    for bundle in sorted(set(bundle_ids(json.loads(data)))):
        for name, sha in expected['blobs'].items():
            path = managed / 'bundles' / bundle / name
            payload = read_small(path)
            if payload is not None:
                report['source_checks'].append({'action': action, 'path': str(path),
                    'expected_blob': sha, 'observed_blob': blob(payload), 'matches': blob(payload) == sha})

# Capture explicit input-generation references, not raw phenotype or genotype data.
for base in (root, root / 'code'):
    for path in sorted(base.glob('*.R')):
        data = read_small(path)
        if data is None:
            continue
        lines = data.decode('utf-8', errors='replace').splitlines()
        matches = [{'line': i + 1, 'text': line} for i, line in enumerate(lines)
                   if any(term in line for term in ('qtls_list_260204', 'iRemapAll.out', 'qtls_list', 'save(qtls'))]
        if matches:
            report['provenance'].append({'path': str(path), 'matches': matches[:50]})
for rel in ('imed/Frank/qtls_list_260204.rda', 'logs/iRemapAll.out'):
    path = root / rel
    if path.is_file():
        report['provenance'].append({'path': str(path), 'size_bytes': path.stat().st_size,
                                    'mtime_ns': path.stat().st_mtime_ns})
git = next((p for p in ('/usr/bin/git', '/bin/git') if Path(p).is_file()), None)
if git:
    report['git'] = {}
    for args in (['rev-parse', 'HEAD'], ['status', '--short']):
        result = subprocess.run([git, '-C', str(root)] + args, capture_output=True, text=True, timeout=20)
        report['git'][' '.join(args)] = {'returncode': result.returncode, 'stdout': result.stdout[:20000], 'stderr': result.stderr[:2000]}
report['files_seen'] = seen
report['selected_actions'] = sorted(selected_actions)
payload = json.dumps(report, indent=2)
if len(payload.encode()) > 3000000:
    raise RuntimeError('Report size limit exceeded')
with (out / 'final_review_audit.json').open('x') as handle:
    handle.write(payload)
print(json.dumps({'results': len(report['results']), 'source_checks': len(report['source_checks']),
                  'errors': report['errors'], 'report': 'final_review_audit.json'}))
